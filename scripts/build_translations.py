def _escape_po(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def write_po(locale: str, translations: dict[str, str], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    header = [
        'msgid ""',
        'msgstr ""',
        '"Project-Id-Version: Open ERP 0.1.0\\n"',
        '"Report-Msgid-Bugs-To: \\n"',
        '"MIME-Version: 1.0\\n"',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        '"Content-Transfer-Encoding: 8bit\\n"',
        f'"Language: {locale}\\n"',
        "",
    ]
    entries: list[str] = []
    for msgid in sorted(translations, key=lambda s: s.lower()):
        msgstr = msgid if locale == "ru" else translations[msgid]
        entries.append(f'msgid "{_escape_po(msgid)}"')
        entries.append(f'msgstr "{_escape_po(msgstr)}"')
        entries.append("")
    path.write_text("\n".join(header + entries), encoding="utf-8")


def main() -> None:
    base = Path(__file__).resolve().parents[1] / "locales"
    write_po("ru", EN, base / "ru" / "LC_MESSAGES" / "messages.po")
    write_po("en", EN, base / "en" / "LC_MESSAGES" / "messages.po")
    print(f"Wrote {len(EN)} strings")


if __name__ == "__main__":
    main()
